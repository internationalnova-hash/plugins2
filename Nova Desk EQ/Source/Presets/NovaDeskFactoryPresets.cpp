// requested Hz value already exists as a stepped choice.
//
// Output: the two values the spec gives explicitly are transcribed as-is
// (Default Channel EQ = 0dB, Vocal Presence = -1dB). Every other preset
// leaves Output as "Gain-match" with no exact number, deliberately left
// at 0dB here rather than filled in with a guess.
//
