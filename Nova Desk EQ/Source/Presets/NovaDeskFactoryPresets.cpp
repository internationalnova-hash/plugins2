// (Source/PresetGainMatch.cpp) and run against all 26 presets. Checked
// against the ONE ground-truth number the spec provides (Vocal Presence,
// -1dB), it disagreed in both magnitude AND SIGN (computed +1.0dB) - pink
// noise has flat energy per octave, but these presets are shaped around
// where real vocal/drum/bass program material actually concentrates
// energy, so a flat broadband probe cannot reliably predict how a
// vocal/drum/bass-targeted EQ curve will land on real material of that
// kind. Since the one number checkable against ground truth was wrong,
// the tool's other 24 outputs were NOT trusted enough to bake in as
// defaults - that would overstate how "done" gain-matching is. The tool
// is kept as a useful diagnostic for a real listening-based pass (spec
// section 31's "AUDITION EVERY PRESET... use appropriate source
// material"), which remains the actual outstanding QA step here.
